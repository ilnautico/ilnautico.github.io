function calculateFoodConfidence(input, scoring, activeTriggers) {

  let evidence = 100;

  if (input.tds_available === 'no') evidence -= 30;
  if (input.tds_available === 'partial') evidence -= 15;

  if (input.supplier_data === 'none') evidence -= 40;
  if (input.supplier_data === 'unknown') evidence -= 25;
  if (input.supplier_data === 'partial') evidence -= 15;

  evidence = Math.max(0, evidence);

  let regulatory = 100;

  const marketCount = (input.target_markets ?? []).length;

  if (marketCount > 1) regulatory -= 10;
  if (marketCount > 2) regulatory -= 10;

  if (input.eol_claim !== 'none' &&
      ['no', 'none'].includes(input.eol_cert ?? '')) {
    regulatory -= 30;
  }

  regulatory = Math.max(0, regulatory);

  let clarity = 100;

  const unknownCount = [
    input.food?.food_type,
    input.food?.contact_temp,
    input.food?.contact_duration,
    input.food?.seal_temp,
    input.food?.inpack_process,
    input.supplier_data,
  ].filter(v =>
    v === 'unknown' ||
    v === undefined ||
    v === null
  ).length;

  clarity -= unknownCount * 10;
  clarity = Math.max(0, clarity);

  let org = 100;

  if (input.internal_ra === 'none' || input.internal_ra === 'no') org -= 40;
  if (input.internal_ra === 'external') org -= 15;

  if (input.regulator_dialogue === 'none') org -= 30;

  org = Math.max(0, org);

  let assumption = unknownCount * 15;
  assumption = Math.min(assumption, 100);

  const hasCriticalTrigger =
    (activeTriggers ?? []).some(t => t.severity === 'critical');

  const hasMajorTrigger =
    (activeTriggers ?? []).some(t => t.severity === 'major');

  if (hasCriticalTrigger) assumption = Math.min(100, assumption + 20);
  else if (hasMajorTrigger) assumption = Math.min(100, assumption + 10);

  const confidence =
    0.35 * evidence +
    0.25 * regulatory +
    0.15 * clarity +
    0.20 * org +
    0.05 * (100 - assumption);

  let score = Math.round(confidence);

  // Evidence-zero cap
  if (evidence <= 30) {
    score = Math.min(score, 45);
  }

  // No TDS + no supplier data cap
  if (input.tds_available === 'no' && input.supplier_data === 'none') {
    score = Math.min(score, 45);
  }

  // Any major/critical technical review flag cap
  const hasMajorOrCriticalTrigger =
    (activeTriggers ?? []).some(t =>
      t.severity === 'major' || t.severity === 'critical'
    );

  if (hasMajorOrCriticalTrigger) {
    score = Math.min(score, 85);
  }

  // Critical trigger cap
  if (hasCriticalTrigger) {
    score = Math.min(score, 70);
  }

  let level;
  if (score >= 80) level = 'High';
  else if (score >= 65) level = 'Structured';
  else if (score >= 50) level = 'Conditional';
  else level = 'Low';

  const rationaleParts = [];

  if (evidence < 85)
    rationaleParts.push('material and supplier evidence is incomplete');

  if (regulatory < 90)
    rationaleParts.push('regulatory or claim-related exposure remains');

  if (clarity < 90)
    rationaleParts.push('application or processing parameters are not fully defined');

  if (org < 90)
    rationaleParts.push('internal regulatory capability or authority dialogue is limited');

  if (assumption > 0)
    rationaleParts.push('the assessment depends on unresolved assumptions');

  const rationale = rationaleParts.length
    ? 'Confidence reflects that ' + rationaleParts.join(', ') + '.'
    : 'Confidence is supported by available evidence, defined application conditions, and limited unresolved assumptions.';

  return {
    score,
    level,
    rationale,
    breakdown: {
      evidence,
      regulatory,
      clarity,
      organisational: org,
      assumptionDependency: assumption,
    },
  };
}





